    'schools','student_profiles','profile_assessments','profile_preferences',
    'advisor_conversations','major_employment_profiles','job_sources','profile_saved_items'
  ] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS %I ON public.%I', 'set_' || table_name || '_updated_at', table_name);
    EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.set_updated_at()', 'set_' || table_name || '_updated_at', table_name);
  END LOOP;
END;
$$;

